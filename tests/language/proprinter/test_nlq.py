def _dots(picture, marks):
    return {
        (column, row)
        for row, line in enumerate(picture.splitlines())
        for column, mark in enumerate(line)
        if mark in marks
    }


@pytest.mark.parametrize("picture", [VERTICAL_LINE, SHALLOW_DIAGONALS, DIAGONAL, T, Z, M, K])
def test_the_printer_adds_the_dots_the_manual_draws(picture):
    draft = Glyph(frozenset((column // 2, row // 2) for column, row in _dots(picture, "#")))
    assert set(nlq_from_draft(draft).dots) == _dots(picture, "#o")


def test_a_dot_standing_alone_moves_to_the_finer_grid():
    assert nlq_from_draft(Glyph(frozenset({(3, 2)}))).dots == {(6, 4)}


def test_no_diagonal_spans_three_columns():
    assert nlq_from_draft(Glyph(frozenset({(1, 0), (4, 1)}))).dots == {(2, 0), (8, 2)}


def test_the_span_doubles_with_the_grid():
    assert nlq_from_draft(Glyph(frozenset(), span=(1, 5))).span == (2, 10)
