LEFT = 1080  # 1/4 inch: the paper edge to column 0
PICA = 432
ELITE = 360
STEP = 36  # 1/120 inch: a draft column at 10 cpi
NLQ_STEP = 18  # 1/240 inch: an NLQ column at 10 cpi
HALF_ROW = 30  # 1/144 inch: NLQ's second pass below its first
PIN = 60  # 1/72 inch
LINE = 720

ESC = b"\x1b"
FS = b"\x1c"


def mechanism(**options):
    """The test mechanism, with the test fonts unless *options* gives others."""
    options.setdefault("font", MemoryDotFont(name="test", text=DRAFT_FONT_TEXT))
    return ProprinterMechanism(**options)


def faces():
    """Options giving the test mechanism Fastfont and NLQ II."""
    return {
        "fastfont": MemoryDotFont(name="test-fastfont", text=FASTFONT_TEXT),
        "nlq_ii_font": MemoryDotFont(name="test-nlq-ii", text=NLQ_II_FONT_TEXT),
    }


def run(data, **options):
    """All pages from *data*, including the part-printed last one."""
    interpreter = ProprinterInterpreter(mechanism(**options))
    return interpreter.feed(data) + interpreter.finish()


def dots(data, **options):
    """The dots of the only page *data* prints."""
    (page,) = run(data, **options)
    return sorted(page.dots)


def text(data, **options):
    """The characters *data* prints, on every page."""
    return "".join(mark.character for page in run(data, **options) for mark in page.text)
